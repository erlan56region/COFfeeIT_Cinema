// GitHub Pages и другие статические хостинги только раздают файлы и не запускают
// server.js. Поэтому комнаты, чат и синхронизация работают через сервер,
// развёрнутый отдельно (Render, Railway, свой VPS — см. README.md),
// а его адрес (обязательно с https://) указывается здесь, например:
//
//   window.SYNCWATCH_SERVER = 'https://syncwatch.onrender.com';
//
// Пустая строка — сервер находится по тому же адресу, что и сам сайт.
// Так и должно быть при обычном запуске через «npm start»: в этом случае
// server.js сам отдаёт сайту пустое значение, и этот файл менять не нужно.
